#!/usr/bin/env python3
"""Generate the built-in MiSTer ROM data from the checked-in upstream snapshot."""

import argparse
import hashlib
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
REVISION = "ac5b7bcb14f5fc6f80b878abd26a94ee5a4a8049"
DATABASE = ROOT / "data/mister/N64-database.txt"
OUTPUT = ROOT / "src/main/rom_database_mister.h"
SAVE_TYPES = {
    "eeprom512": "SAVETYPE_EEPROM_4K",
    "eeprom2k": "SAVETYPE_EEPROM_16K",
    "sram32k": "SAVETYPE_SRAM",
    "sram96k": "SAVETYPE_SRAM",
    "flash128k": "SAVETYPE_FLASH_RAM",
}
FLAGS = {
    "cpak": "MISTER_MEMPAK",
    "rpak": "MISTER_RUMBLE",
    "tpak": "MISTER_TRANSFERPAK",
    "ntsc": "MISTER_NTSC",
    "pal": "MISTER_PAL",
}
PREAMBLE = """#ifndef N64EMU_ROM_DATABASE_MISTER_H
#define N64EMU_ROM_DATABASE_MISTER_H

#include <stdint.h>
#include "core/types.h"

enum {
    MISTER_SAVE_MASK = 7,
    MISTER_MEMPAK = 1 << 3,
    MISTER_RUMBLE = 1 << 4,
    MISTER_TRANSFERPAK = 1 << 5,
    MISTER_NTSC = 1 << 6,
    MISTER_PAL = 1 << 7,
};

"""


def parse_settings(tags):
    save = "SAVETYPE_NONE"
    flags = []
    for tag in filter(None, tags.split("|")):
        if tag in SAVE_TYPES:
            if save != "SAVETYPE_NONE":
                raise ValueError("multiple save types")
            save = SAVE_TYPES[tag]
        elif tag in FLAGS:
            if tag in ("ntsc", "pal") and any(region in flags for region in ("MISTER_NTSC", "MISTER_PAL")):
                raise ValueError("multiple regions")
            flags.append(FLAGS[tag])
        elif tag not in ("rtc", "noepak") and not re.fullmatch(
            r"cic(?:[0-9]{4}|ddus)|p[0-9a-f]+:[0-9a-f]{8}(?::t)?", tag, re.IGNORECASE
        ):
            raise ValueError(f"unknown tag {tag!r}")
    return " | ".join([save, *flags])


def generate(source, revision):
    hashes = {}
    cartridge_ids = {}
    for number, line in enumerate(source.decode("utf-8-sig").splitlines(), 1):
        fields = re.split(r"[#;]", line, maxsplit=1)[0].split()
        if not fields:
            continue
        key, *tags = fields
        try:
            if len(tags) > 1:
                raise ValueError("expected a single pipe-delimited tag list")
            if re.fullmatch(r"[0-9a-fA-F]{32}", key):
                table, identifier = hashes, bytes.fromhex(key)
            elif re.fullmatch(r"ID:[A-Z0-9_]{1,6}", key):
                table, identifier = cartridge_ids, key[3:].ljust(6, "_")
            else:
                raise ValueError(f"invalid ROM key {key!r}")
            if identifier in table:
                raise ValueError(f"duplicate ROM key {key!r}")
            table[identifier] = parse_settings(tags[0] if tags else "")
        except ValueError as error:
            raise ValueError(f"line {number}: {error}") from error

    if not hashes or not cartridge_ids:
        raise ValueError("the snapshot must contain both hashes and cartridge IDs")

    lines = [
        "/* Generated by tools/update_mister_rom_database.py; do not edit.",
        " * SPDX-License-Identifier: GPL-3.0-only",
        f" * Source: https://github.com/MiSTer-devel/N64_ROM_Database/blob/{revision}/N64-database.txt",
        f" * Source SHA-256: {hashlib.sha256(source).hexdigest()}",
        f" * {len(hashes)} hashes and {len(cartridge_ids)} cartridge ID patterns.",
        " * See data/mister/LICENSE for the upstream license.",
        " */",
        "",
        PREAMBLE.rstrip(),
        "",
        "static const struct { uint8_t md5[16]; uint8_t settings; } mister_md5_entries[] = {",
    ]
    for key, settings in sorted(hashes.items()):
        digest = ", ".join(f"0x{byte:02x}" for byte in key)
        lines.append(f"    {{{{{digest}}}, {settings}}},")
    lines.extend(["};", "", "static const struct { char pattern[7]; uint8_t settings; } mister_cart_entries[] = {"])
    lines.extend(f'    {{"{pattern}", {settings}}},' for pattern, settings in cartridge_ids.items())
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines), len(hashes), len(cartridge_ids)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DATABASE)
    parser.add_argument("--revision", default=REVISION)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not re.fullmatch(r"[0-9a-f]{40}", args.revision):
        parser.error("--revision must be a complete MiSTer commit hash")
    generated, hashes, patterns = generate(args.source.read_bytes(), args.revision)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("MiSTer ROM database header is out of date")
    else:
        OUTPUT.write_bytes(generated.encode("utf-8"))
    print(f"MiSTer ROM database: {hashes} hashes, {patterns} cartridge ID patterns")


if __name__ == "__main__":
    main()
